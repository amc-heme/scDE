# The same fixture through every object class and both SCUBA engines gives identical edgeR tables.

test_that("Seurat Assay5, legacy Assay, in-memory SCE and the pre-aggregated path agree", {
  skip_if_no_edger()
  skip_if_no_scuba_pseudobulk()
  skip_if_not_installed("SeuratObject")
  skip_if_not_installed("SingleCellExperiment")
  withr::local_options(list(SCUBA.engine = "r"))
  fixture <- edger_fixture(FALSE)
  reference <- suppressWarnings(run_dge(fixture_pseudobulk(fixture), test_use = "edgeR", group_1 = "group_1", group_2 = "group_2"))
  expect_edger_result(reference, "independent")
  seurat <- as_seurat(fixture)
  expect_s4_class(seurat[["RNA"]], "Assay5")
  expect_equal(sorted_result(run_fixture_edger(seurat)), sorted_result(reference), tolerance = 1e-10)
  legacy <- as_legacy_seurat(fixture)
  result <- suppressWarnings(run_dge(legacy, "condition", layer = "counts", seurat_assay = "legacy", test_use = "edgeR",
                                     sample_by = "sample_id", group_1 = "group_1", group_2 = "group_2"))
  expect_equal(sorted_result(result), sorted_result(reference), tolerance = 1e-10)
  expect_identical(attr(result, "edger_details")$aggregation$assay, "legacy")
  sce <- as_sce(fixture)
  expect_equal(sorted_result(run_fixture_edger(sce)), sorted_result(reference), tolerance = 1e-10)
  expect_identical(attr(run_fixture_edger(sce), "edger_details")$aggregation$source_class, "SingleCellExperiment")
  pb <- SCUBA::pseudobulk(sce, "sample_id", "condition")
  expect_equal(sorted_result(suppressWarnings(run_dge(pb, test_use = "edgeR", group_1 = "group_1", group_2 = "group_2"))),
               sorted_result(reference), tolerance = 1e-10)
})

